-- 0) Función de rol administrador (se asegura que exista).
create or replace function public.is_admin()
returns boolean
language sql stable security definer set search_path=''
as $$
  select exists (
    select 1 from public.profiles p
    where p.id=(select auth.uid()) and lower(coalesce(p.rol,''))='admin' and p.activo=true
  );
$$;
grant execute on function public.is_admin() to authenticated;

-- 1) Luis Isidro = administrador. No modifica a los demás usuarios.
update public.profiles p
set rol='admin', activo=true
from auth.users u
where p.id=u.id and lower(u.email)=lower('lisidro@drelm.gob.pe');

-- 2) Soporte de seguimiento requerido por la app (faltaba en la base verificada).
alter table public.visitas add column if not exists visita_origen_id uuid references public.visitas(id) on delete set null;
alter table public.visitas add column if not exists numero_visita integer;

create table if not exists public.medidas_correctivas (
  id uuid primary key default gen_random_uuid(),
  visita_id uuid not null references public.visitas(id) on delete cascade,
  variable text not null,
  cbc text,
  codigo_indicador text,
  codigo_medida text not null,
  medida text not null,
  responsable text,
  plazo_dias integer,
  fecha_vencimiento date,
  estado text not null default 'Pendiente' check (estado in ('Pendiente','En proceso','Subsanada')),
  seguimiento text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(visita_id,variable,codigo_medida)
);
alter table public.medidas_correctivas enable row level security;
grant select,insert,update,delete on public.medidas_correctivas to authenticated;

drop policy if exists medidas_read on public.medidas_correctivas;
create policy medidas_read on public.medidas_correctivas for select to authenticated
using (exists(select 1 from public.visitas v where v.id=visita_id));
drop policy if exists medidas_insert on public.medidas_correctivas;
create policy medidas_insert on public.medidas_correctivas for insert to authenticated
with check (exists(select 1 from public.visitas v where v.id=visita_id and ((v.user_id=(select auth.uid()) and v.estado='Borrador') or public.is_admin())));
drop policy if exists medidas_update on public.medidas_correctivas;
create policy medidas_update on public.medidas_correctivas for update to authenticated
using (exists(select 1 from public.visitas v where v.id=visita_id and ((v.user_id=(select auth.uid()) and v.estado='Borrador') or public.is_admin())))
with check (exists(select 1 from public.visitas v where v.id=visita_id and ((v.user_id=(select auth.uid()) and v.estado='Borrador') or public.is_admin())));
drop policy if exists medidas_delete on public.medidas_correctivas;
create policy medidas_delete on public.medidas_correctivas for delete to authenticated
using (public.is_admin());

